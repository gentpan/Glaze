import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { runInNewContext } from 'node:vm';
import { blogIcons } from '../src/icons/blog.mjs';

const [kubaiPath, simpleIconsPath] = process.argv.slice(2);
if (!kubaiPath || !simpleIconsPath) {
  throw new Error('Usage: node tools/menu-icons.mjs <Kubai src/engine.js> <Simple Icons icons.json>');
}

const geometry = runInNewContext(readFileSync(kubaiPath, 'utf8') + '\n({ rr });');
const { icons, aliases } = JSON.parse(readFileSync(simpleIconsPath, 'utf8'));
const groups = blogIcons(geometry);
const brands = [
  ['x', 'X / Twitter'], ['sinaweibo', 'Sina Weibo', '新浪微博'], ['github', 'GitHub'],
  ['xiaohongshu', 'Xiaohongshu', '小红书'], ['wechat', 'WeChat', '微信'], ['tencentqq', 'QQ'],
  ['bilibili', 'Bilibili', '哔哩哔哩'], ['tiktok', 'TikTok / Douyin', 'TikTok / 抖音'], ['zhihu', 'Zhihu', '知乎'],
  ['telegram', 'Telegram'], ['youtube', 'YouTube'], ['instagram', 'Instagram'], ['facebook', 'Facebook'],
  ['threads', 'Threads'], ['mastodon', 'Mastodon'], ['bluesky', 'Bluesky'], ['reddit', 'Reddit'],
  ['discord', 'Discord'], ['linkedin', 'LinkedIn'], ['gitlab', 'GitLab'], ['twitch', 'Twitch'],
  ['pinterest', 'Pinterest'], ['medium', 'Medium'], ['dribbble', 'Dribbble'], ['codepen', 'CodePen'],
  ['stackoverflow', 'Stack Overflow'], ['npm', 'npm'],
];

const out = new URL('../assets/images/menu-icons/', import.meta.url);
mkdirSync(out, { recursive: true });
for (const entries of Object.values(groups)) {
  for (const [id, , , body] of entries) {
    const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 -2 31 29"><g fill="none" stroke="currentColor" stroke-width="1.65" stroke-linecap="round" stroke-linejoin="round">${body}</g></svg>\n`;
    writeFileSync(new URL(`${id}.svg`, out), svg);
  }
}

groups.social = brands.map(([id, label, chinese]) => {
  const icon = icons[id] || icons[aliases?.[id]?.parent];
  if (!icon) throw new Error(`Missing brand icon: ${id}`);
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24">${icon.body}</svg>\n`;
  writeFileSync(new URL(`social-${id}.svg`, out), svg);
  return [`social-${id}`, label, chinese];
});

const php = Object.entries(groups).map(([group, entries]) =>
  `\t\t'${group}' => array(\n` +
  entries.map(([id, label]) => `\t\t\t'${id}' => __( '${label}', 'glaze' ),`).join('\n') +
  '\n\t\t),'
).join('\n');
writeFileSync(new URL('../inc/icon-catalog.php', import.meta.url), `<?php
defined( 'ABSPATH' ) || exit;

function westnote_glaze_icon_catalog() {
	return array(
${php}
	);
}
`);

const css = Object.values(groups).flatMap((entries) => entries.map(([id]) => id)).sort().map((id) =>
  `[data-glaze-icon="${id}"] { --glaze-icon-image: url("../images/menu-icons/${id}.svg"); }`
).join('\n');
writeFileSync(new URL('../src/css/components/menu-icons.css', import.meta.url), `/* Generated by tools/menu-icons.mjs. */\n${css}\n`);

const locale = new URL('../languages/zh_CN.po', import.meta.url);
const existing = readFileSync(locale, 'utf8');
const messages = new Map();
for (const entries of Object.values(groups)) {
  for (const [, label, chinese] of entries) {
    const key = `msgid ${JSON.stringify(label)}\n`;
    if (chinese && !existing.includes(key)) messages.set(key, chinese);
  }
}
if (messages.size) {
  const entries = [...messages].map(([key, chinese]) => key + `msgstr ${JSON.stringify(chinese)}\n`);
  writeFileSync(locale, existing.trimEnd() + '\n\n' + entries.join('\n'));
}
